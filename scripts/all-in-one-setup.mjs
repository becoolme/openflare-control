#!/usr/bin/env node
// One-shot operator setup for docker-compose.all-in-one.yml: generates the
// required secrets into `.env` (compose reads it for interpolation and for
// the `environment:`-sourced secrets). Idempotent — refuses to overwrite an
// existing .env unless --force is passed, because rotating
// PLANE_SIGNING_SECRET/PLANE_SECRETS_KEY underneath a live plane breaks
// snapshot verification and at-rest secret decryption.
//
//   node scripts/all-in-one-setup.mjs [--force]

import { randomBytes } from 'node:crypto'
import { existsSync, writeFileSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, '.env')
const force = process.argv.includes('--force')

if (existsSync(target) && !force) {
  const age = Math.round((Date.now() - statSync(target).mtimeMs) / 1000)
  console.error(`.env already exists (${age}s old) — refusing to overwrite.`)
  console.error('Rotating secrets under a live deployment breaks verification;')
  console.error('pass --force only when you know why you are doing it.')
  process.exit(1)
}

const hex = (n) => randomBytes(n).toString('hex')
const lines = [
  '# Generated by scripts/all-in-one-setup.mjs — never commit this file.',
  `# ${new Date().toISOString()}`,
  '',
  '# --- required secrets (compose fails closed without them) ---',
  `PLANE_ADMIN_TOKEN=${hex(32)}`,
  `PLANE_SIGNING_SECRET=${hex(32)}`,
  `PLANE_SECRETS_KEY=${hex(32)}`,
  `CONSOLE_AUTH_PASSWORD=${hex(16)}`,
  `POSTGRES_PASSWORD=${hex(16)}`,
  `REDIS_PASSWORD=${hex(16)}`,
  '',
  '# --- image set (pin a release tag; see release-images workflow) ---',
  '# OPENFLARE_REGISTRY=ghcr.io/becoolme',
  '# OPENFLARE_IMAGE_TAG=v0.7.4',
  '',
  '# --- optional ingress/TLS overrides ---',
  '# VRT_BIND=127.0.0.1        # tenant ingress bind (port 8080)',
  '# CONSOLE_HOST=localhost    # TLS-profile console hostname',
  '# VRT_TLS_EMAIL=you@example.com',
  '',
]
writeFileSync(target, lines.join('\n'), { mode: 0o600 })
console.log(`wrote ${target} (mode 0600)`)
console.log('')
console.log('next:')
console.log('  docker compose -f docker-compose.all-in-one.yml up -d')
console.log('  node scripts/hello-all-in-one.mjs')
