import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { buildRuntimeBundle, canonicalJson, verifyRuntimeBundle } from '../src/index.js'

const digest = 'a71da14134a9249da38199c2fc282347a451237a1702c9758214f026a809753f'
const fixture = (): Uint8Array =>
  readFileSync(join(__dirname, 'fixtures', 'runtime-bundle-v1.json'))

describe('runtime bundle format', () => {
  it('accepts the stored document generated by the real runtime', () => {
    expect(verifyRuntimeBundle(digest, fixture())).toBe(true)
  })

  it('rebuilds the same manifest digest from the stored modules', () => {
    const doc = JSON.parse(Buffer.from(fixture()).toString('utf8'))
    const built = buildRuntimeBundle({
      mainModule: doc.mainModule,
      modules: doc.modules,
      compatibilityDate: doc.compatibilityDate,
      compatibilityFlags: doc.compatibilityFlags,
    })
    expect(built.digest).toBe(digest)
    expect(verifyRuntimeBundle(built.digest, built.bytes)).toBe(true)
  })

  it('rejects tampering, a wrong digest and malformed documents', () => {
    const doc = JSON.parse(Buffer.from(fixture()).toString('utf8'))
    doc.modules[0].text = 'export default { fetch() { return new Response("evil") } }'
    const tampered = Buffer.from(canonicalJson(doc))
    expect(verifyRuntimeBundle(digest, tampered)).toBe(false)
    expect(verifyRuntimeBundle('f'.repeat(64), fixture())).toBe(false)
    expect(verifyRuntimeBundle(digest, Buffer.from('not json'))).toBe(false)
    expect(verifyRuntimeBundle(digest, Buffer.from('{"schemaVersion":2}'))).toBe(false)
  })

  it('sorts canonical JSON keys and rejects unsafe input', () => {
    expect(canonicalJson({ b: 1, a: [true, null, 'x'] })).toBe('{"a":[true,null,"x"],"b":1}')
    expect(() => canonicalJson(Number.POSITIVE_INFINITY)).toThrow()
    expect(() =>
      buildRuntimeBundle({
        mainModule: 'main.js',
        modules: [{ type: 'text', name: 'main.js', text: 'x' }],
        compatibilityDate: 'not-a-date',
      })
    ).toThrow()
  })
})
